#include "libft.h"

int	ft_atoi(const char *str)
{
	int				i;
	int				j;
	unsigned long	res;

	i = 0;
	j = 1;
	res = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == 32)
		i++;
	if (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			j = -1;
		i++;
	}
	while (str[i] >= 48 && str[i] <= 57)
	{
		res = res * 10 + str[i] - 48;
		if (res > 9223372036854775807)
			return (-(j > 0));
		i++;
	}
	if (j < 0)
		res = res * (-1);
	return (res);
}
