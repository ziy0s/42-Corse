#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	const unsigned char	*p;
	size_t				i;

	p = s;
	i = 0;
	while (n > i)
	{
		if (p[i] == (unsigned char) c)
			return ((void *)(p + i));
		i++;
	}
	return (NULL);
}
