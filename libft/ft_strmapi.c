#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char	*p;
	int		i;

	i = 0;
	if (s == NULL || f == NULL)
		return (NULL);
	p = malloc(ft_strlen(s) + 1);
	if (p == NULL)
		return (p);
	while (s[i])
	{
		p[i] = f(i, s[i]);
		i++;
	}
	p[i] = '\0';
	return (p);
}
